// Recolor produces a character-substitution map, used to derive Dario's
// "Aligned" palette from his base sprites without redrawing them.
func Recolor(pairs ...byte) map[byte]byte {
	m := map[byte]byte{}
	for i := 0; i+1 < len(pairs); i += 2 {
		m[pairs[i]] = pairs[i+1]
	}
	return m
}

// alignedSwap repaints Dario's navy blazer coral and his shirt cream, giving
// the "Constitution Scroll" form a silhouette that reads instantly at a
// glance without redrawing a single frame.
var alignedSwap = Recolor(
	'h', '7', // blazer shadow -> coral dark
	'g', '6', // blazer        -> coral
	'i', '4', // shirt         -> cream
)
