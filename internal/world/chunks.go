package world

// Levels are assembled from hand-authored chunks. Each chunk is bottom-aligned
// against the floor of the level, so a chunk only needs as many rows as it
// actually uses. The standard surface chunk is 12 rows tall with ground at
// rows 9-11, which puts the walkable surface four-and-a-bit tiles below the
// top of a jump.
//
// See tile.go for the character alphabet.

type Chunk struct {
	Rows []string
}

func (c Chunk) Width() int {
	if len(c.Rows) == 0 {
		return 0
	}
	return len(c.Rows[0])
}

